#!/usr/bin/env node
/* eslint-env node */

import { writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { validateReleaseIdentity } from "./release/validate-identity.mjs";
import { ProvenanceError } from "./release/git-identity.mjs";

// Dual-accept release mode (AROKO_* preferred).
const releaseModeRaw = (
  process.env.AROKO_RELEASE_MODE?.trim() ||
  process.env.PAIRMESH_RELEASE_MODE?.trim() ||
  ""
).toLowerCase();
const mode = releaseModeRaw === "release" ? "release" : "development";

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), "..");
const targetPath = join(repoRoot, "packages/client/src/build-info.generated.ts");

function main() {
  let validated;
  try {
    validated = validateReleaseIdentity(repoRoot, mode);
  } catch (error) {
    if (error instanceof ProvenanceError && mode === "development") {
      console.error(`build-info: ${error.code}: ${error.message}`);
      process.exit(1);
    }
    throw error;
  }

  const buildId =
    mode === "release"
      ? validated.releaseId
      : validated.isDirty
        ? `dev-dirty-${validated.gitCommit.slice(0, 12)}`
        : validated.releaseId;

  const buildTimestamp = validated.sourceTimestamp;

  const contents = `/** Generated by scripts/generate-build-info.mjs — do not edit. */
export const AROKO_VERSION = ${JSON.stringify(validated.packageVersion)};
export const AROKO_BUILD_ID = ${JSON.stringify(buildId)};
export const AROKO_BUILD_TIMESTAMP = ${JSON.stringify(buildTimestamp)};
export const AROKO_GIT_COMMIT = ${JSON.stringify(validated.gitCommit)};
export const AROKO_GIT_TAG = ${JSON.stringify(validated.gitTag ?? "")};
export const AROKO_RELEASE_ID = ${JSON.stringify(validated.releaseId)};
export const AROKO_PROTOCOL_VERSION = ${JSON.stringify(validated.protocolVersion)};
export const AROKO_STATE_SCHEMA_VERSION = ${JSON.stringify(validated.stateSchemaVersion)};
export const AROKO_IS_DIRTY = ${validated.isDirty ? "true" : "false"};
export const AROKO_BUILD_MODE = ${JSON.stringify(mode)};

/** @deprecated Use AROKO_* — PairMesh compatibility aliases (S23-4). */
export const PAIRMESH_VERSION = AROKO_VERSION;
export const PAIRMESH_BUILD_ID = AROKO_BUILD_ID;
export const PAIRMESH_BUILD_TIMESTAMP = AROKO_BUILD_TIMESTAMP;
export const PAIRMESH_GIT_COMMIT = AROKO_GIT_COMMIT;
export const PAIRMESH_GIT_TAG = AROKO_GIT_TAG;
export const PAIRMESH_RELEASE_ID = AROKO_RELEASE_ID;
export const PAIRMESH_PROTOCOL_VERSION = AROKO_PROTOCOL_VERSION;
export const PAIRMESH_STATE_SCHEMA_VERSION = AROKO_STATE_SCHEMA_VERSION;
export const PAIRMESH_IS_DIRTY = AROKO_IS_DIRTY;
export const PAIRMESH_BUILD_MODE = AROKO_BUILD_MODE;
`;

  mkdirSync(dirname(targetPath), { recursive: true });
  writeFileSync(targetPath, contents, "utf8");
  console.log(
    `Generated ${targetPath} (${buildId}, commit ${validated.gitCommit.slice(0, 12)}, mode=${mode})`
  );
}

try {
  main();
} catch (error) {
  if (error instanceof ProvenanceError) {
    console.error(`PROVENANCE_${error.code}: ${error.message}`);
    process.exit(1);
  }
  console.error(error instanceof Error ? error.message : String(error));
  process.exit(1);
}
